//Switch case
const month = 4
switch (month) {
    case 1:
        console.log("January");
        break;
    case 2:
        console.log("February");
        break;
    case 3:
        console.log("March");
        break;
    case 4:
        console.log("April");             //April
        break;
    case 5:
        console.log("May");
        break;

    default:
        console.log("Default case match");
        break;
}